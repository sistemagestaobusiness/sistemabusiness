-- ---------------------------------------------------------------- regras de acesso por espaço
do $$
declare t text;
begin
  foreach t in array array['contas','clientes','fornecedores','categorias','recorrencias','lancamentos','extrato_linhas'] loop
    execute format('drop policy %I on public.%I', t || '_ler', t);
    execute format('drop policy %I on public.%I', t || '_incluir', t);
    execute format('drop policy %I on public.%I', t || '_alterar', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.pode_ler_espaco(espaco_id))', t || '_ler', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.eh_socio_espaco(espaco_id))', t || '_incluir', t);
    execute format('create policy %I on public.%I for update to authenticated using (public.eh_socio_espaco(espaco_id)) with check (public.eh_socio_espaco(espaco_id))', t || '_alterar', t);
  end loop;
end $$;

-- histórico de alterações: cada um vê só o do espaço em que é sócio
create or replace function public.tg_auditoria() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.auditoria (tabela, registro_id, acao, antes, depois, espaco_id)
  values (tg_table_name,
          coalesce((to_jsonb(new) ->> 'id'), (to_jsonb(old) ->> 'id')),
          tg_op,
          case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
          case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end,
          case when tg_table_name = 'espacos' then coalesce((to_jsonb(new) ->> 'id'), (to_jsonb(old) ->> 'id'))
               else coalesce((to_jsonb(new) ->> 'espaco_id'), (to_jsonb(old) ->> 'espaco_id')) end::bigint);
  return coalesce(new, old);
end $$;
drop policy auditoria_ler on public.auditoria;
