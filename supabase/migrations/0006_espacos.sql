  using (public.eh_socio_espaco(coalesce(espaco_id, 1)));

-- ---------------------------------------------------------------- saldos por espaço
drop function public.fn_saldo_ate(date);
create function public.fn_saldo_ate(p_data date, p_espaco bigint default 1) returns numeric
language sql stable security invoker set search_path = public as $$
  select coalesce((select sum(c.saldo_inicial) from public.contas c where c.espaco_id = p_espaco and c.data_inicial <= p_data), 0)
       + coalesce((select sum(case when k.tipo = 'ENTRADA' then l.valor else -l.valor end)
                     from public.lancamentos l join public.categorias k on k.id = l.categoria_id
                    where l.espaco_id = p_espaco and l.excluido_em is null and l.data < p_data), 0)
$$;
revoke execute on function public.fn_saldo_ate(date, bigint) from public, anon;
grant execute on function public.fn_saldo_ate(date, bigint) to authenticated;

drop function public.fn_saldo_banco(date, date);
create function public.fn_saldo_banco(p_ini date, p_fim date, p_espaco bigint default 1)
returns table (data date, saldo numeric)
language sql stable security invoker set search_path = public as $$
  with lim as (
    select c.id, c.saldo_banco, c.saldo_banco_em,
           min(e.data) - 1 as de,
           greatest(c.saldo_banco_em, max(e.data)) as ate
      from public.contas c
      join public.extrato_linhas e on e.conta_id = c.id
     where c.espaco_id = p_espaco and c.saldo_banco is not null and c.saldo_banco_em is not null
     group by c.id
  ), dias as (
    select d::date as data from generate_series(p_ini, p_fim, interval '1 day') d
  )
  select dias.data,
         sum(lim.saldo_banco
             + coalesce((select sum(e.valor) from public.extrato_linhas e where e.conta_id = lim.id and e.data <= dias.data), 0)
             - coalesce((select sum(e.valor) from public.extrato_linhas e where e.conta_id = lim.id and e.data <= lim.saldo_banco_em), 0))
    from dias join lim on dias.data between lim.de and lim.ate
   group by dias.data
   order by dias.data
$$;
revoke execute on function public.fn_saldo_banco(date, date, bigint) from public, anon;
grant execute on function public.fn_saldo_banco(date, date, bigint) to authenticated;

