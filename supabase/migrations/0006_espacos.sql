-- lançamento, projeção e linha do extrato herdam o espaço da linha do fluxo / da conta,
-- e não podem misturar espaços (ex.: lançamento pessoal numa conta da Business)
create or replace function public.tg_espaco_herdado() returns trigger
language plpgsql security definer set search_path = public as $$
declare e_cat bigint; e_conta bigint; e_cli bigint; e_forn bigint;
begin
  if tg_table_name in ('lancamentos', 'recorrencias') then
    select espaco_id into e_cat from public.categorias where id = new.categoria_id;
    if new.conta_id is not null then select espaco_id into e_conta from public.contas where id = new.conta_id; end if;
    if e_cat is null then raise exception 'Linha do fluxo não existe'; end if;
    if e_conta is not null and e_conta <> e_cat then raise exception 'A conta e a linha do fluxo são de controles diferentes'; end if;
    new.espaco_id := e_cat;
  elsif tg_table_name = 'extrato_linhas' then
    select espaco_id into e_conta from public.contas where id = new.conta_id;
    if e_conta is null then raise exception 'Conta não existe'; end if;
    new.espaco_id := e_conta;
  elsif tg_table_name = 'categorias' then
    if new.cliente_id is not null then select espaco_id into e_cli from public.clientes where id = new.cliente_id; end if;
    if new.fornecedor_id is not null then select espaco_id into e_forn from public.fornecedores where id = new.fornecedor_id; end if;
    if (e_cli is not null and e_cli <> new.espaco_id) or (e_forn is not null and e_forn <> new.espaco_id) then
      raise exception 'O cliente/fornecedor é de outro controle';
    end if;
  end if;
  if tg_op = 'UPDATE' and new.espaco_id <> old.espaco_id then
    raise exception 'Não é possível mudar o registro de controle';
  end if;
  return new;
end $$;
revoke execute on function public.tg_espaco_herdado() from public, anon, authenticated;

