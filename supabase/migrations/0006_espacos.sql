-- Sistema Business · 0006 · espaços: Business e controles separados (ex.: pessoal do Alexandre)
-- Cada espaço tem as próprias contas, linhas do fluxo, clientes, lançamentos, projeções e extratos.
-- Quem vê cada espaço está em espaco_membros. A separação é feita pelas regras do banco (RLS),
-- não pela tela: quem não é membro de um espaço não recebe nenhuma linha dele, nem pelo tempo real.
-- Tudo o que existe hoje passa a ser do espaço 1 (Business), com os mesmos acessos de antes.

create table public.espacos (
  id        bigint generated by default as identity primary key,
  nome      text not null,
  criado_em timestamptz not null default now()
);
insert into public.espacos (id, nome) values (1, 'Business');
select setval(pg_get_serial_sequence('public.espacos', 'id'), 1);

create table public.espaco_membros (
  espaco_id bigint not null references public.espacos(id),
  user_id   uuid not null references auth.users(id) on delete cascade,
  papel     text not null check (papel in ('SOCIO', 'CONTABILIDADE')),
  primary key (espaco_id, user_id)
);
-- quem já acessa hoje continua acessando a Business, com o mesmo papel
insert into public.espaco_membros (espaco_id, user_id, papel) select 1, user_id, papel from public.perfis;

-- ---------------------------------------------------------------- quem pode o quê, por espaço
create or replace function public.pode_ler_espaco(p_espaco bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.espaco_membros m join public.perfis p on p.user_id = m.user_id
                  where m.user_id = auth.uid() and m.espaco_id = p_espaco and p.ativo)
$$;
create or replace function public.eh_socio_espaco(p_espaco bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.espaco_membros m join public.perfis p on p.user_id = m.user_id
                  where m.user_id = auth.uid() and m.espaco_id = p_espaco and m.papel = 'SOCIO' and p.ativo)
$$;
-- espaço usado quando a gravação não diz qual: só existe se a pessoa for sócia de um espaço só
create or replace function public.fn_espaco_padrao() returns bigint
language sql stable security definer set search_path = public as $$
  select case when count(*) = 1 then min(m.espaco_id) end
    from public.espaco_membros m where m.user_id = auth.uid() and m.papel = 'SOCIO'
$$;
revoke execute on function public.pode_ler_espaco(bigint), public.eh_socio_espaco(bigint), public.fn_espaco_padrao() from public, anon;
grant execute on function public.pode_ler_espaco(bigint), public.eh_socio_espaco(bigint), public.fn_espaco_padrao() to authenticated;

